#!/usr/bin/env bash
# SPDX-License-Identifier: GPL-3.0-or-later
# lrd-cgroup-enforce.sh — Apply cgroup v2 resource limits to LibreDroid slices
# Writes systemd drop-in overrides and reloads daemon.

set -euo pipefail

readonly TAG="lrd-cgroup"
readonly MEMINFO="/proc/meminfo"
readonly DOMAINS_SLICE_D="/etc/systemd/system/lrd-domains.slice.d"
readonly LRD_SLICE_D="/etc/systemd/system/lrd.slice.d"
readonly DOMAINS_DROP_IN="${DOMAINS_SLICE_D}/50-lrd-resource-limits.conf"
readonly LRD_DROP_IN="${LRD_SLICE_D}/50-lrd-resource-limits.conf"

log()  { logger -t "${TAG}" -- "$*"; }
info() { log "INFO  $*"; }
warn() { log "WARN  $*"; }
die()  { log "ERROR $*"; exit 1; }

# ---------------------------------------------------------------------------
# Detect total RAM from /proc/meminfo, return bytes
# ---------------------------------------------------------------------------
get_total_ram_kb() {
    local kb
    kb=$(awk '/^MemTotal:/ { print $2 }' "${MEMINFO}")
    if [[ -z "${kb}" ]]; then
        die "Cannot read MemTotal from ${MEMINFO}"
    fi
    echo "${kb}"
}

# ---------------------------------------------------------------------------
# Calculate 80% of RAM in bytes for MemoryMax
# ---------------------------------------------------------------------------
calc_memory_max() {
    local total_kb="${1}"
    # 80% rounded down to nearest MiB
    local max_kb=$(( total_kb * 80 / 100 ))
    # Convert to bytes
    echo $(( max_kb * 1024 ))
}

# ---------------------------------------------------------------------------
# Write drop-in for lrd-domains.slice (strict multi-domain container slice)
# ---------------------------------------------------------------------------
write_domains_dropin() {
    local memory_max_bytes="${1}"
    mkdir -p "${DOMAINS_SLICE_D}"
    cat > "${DOMAINS_DROP_IN}" <<DROPIN
# Auto-generated by lrd-cgroup-enforce.sh — do not edit manually
# SPDX-License-Identifier: GPL-3.0-or-later
[Slice]
# Memory: cap at 80% of physical RAM to prevent OOM cascade
MemoryAccounting=yes
MemoryMax=${memory_max_bytes}
MemorySwapMax=0

# CPU: allow up to 8 logical cores equivalent (800% = 8 * 100%)
CPUAccounting=yes
CPUQuota=800%

# Tasks: hard cap to prevent fork bombs across all domain services
TasksAccounting=yes
TasksMax=512

# IO accounting (no hard limit — handled per-service)
IOAccounting=yes
DROPIN
    info "Wrote ${DOMAINS_DROP_IN} (MemoryMax=${memory_max_bytes} bytes)"
}

# ---------------------------------------------------------------------------
# Write drop-in for lrd.slice (top-level LibreDroid slice)
# ---------------------------------------------------------------------------
write_lrd_dropin() {
    local memory_max_bytes="${1}"
    mkdir -p "${LRD_SLICE_D}"
    cat > "${LRD_DROP_IN}" <<DROPIN
# Auto-generated by lrd-cgroup-enforce.sh — do not edit manually
# SPDX-License-Identifier: GPL-3.0-or-later
[Slice]
# Memory: soft ceiling at 80% physical RAM for entire lrd stack
MemoryAccounting=yes
MemoryMax=${memory_max_bytes}
MemorySwapMax=0

# CPU: uncapped at slice level; individual services set their own quotas
CPUAccounting=yes

# Tasks: overall cap for the entire LibreDroid userspace
TasksAccounting=yes
TasksMax=1024

IOAccounting=yes
DROPIN
    info "Wrote ${LRD_DROP_IN} (MemoryMax=${memory_max_bytes} bytes)"
}

# ---------------------------------------------------------------------------
# Verify cgroup v2 is mounted
# ---------------------------------------------------------------------------
check_cgroup_v2() {
    if ! grep -q "cgroup2" /proc/mounts 2>/dev/null; then
        die "cgroup v2 is not mounted. Ensure systemd boots with cgroup_no_v1=all or GRUB_CMDLINE_LINUX includes 'systemd.unified_cgroup_hierarchy=1'"
    fi
    info "cgroup v2 confirmed mounted"
}

# ---------------------------------------------------------------------------
# Reload systemd to pick up new drop-ins
# ---------------------------------------------------------------------------
reload_systemd() {
    info "Running systemctl daemon-reload"
    systemctl daemon-reload
    info "daemon-reload complete"
}

# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------
main() {
    if [[ "${EUID}" -ne 0 ]]; then
        die "Must run as root"
    fi

    check_cgroup_v2

    local total_kb
    total_kb=$(get_total_ram_kb)
    info "Detected total RAM: ${total_kb} KiB"

    local memory_max_bytes
    memory_max_bytes=$(calc_memory_max "${total_kb}")
    info "Calculated MemoryMax (80%%): ${memory_max_bytes} bytes ($(( memory_max_bytes / 1024 / 1024 )) MiB)"

    write_domains_dropin "${memory_max_bytes}"
    write_lrd_dropin      "${memory_max_bytes}"

    reload_systemd

    info "cgroup v2 resource limits applied successfully"
}

main "$@"
